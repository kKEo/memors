// Package book generates the scenario pages of the tester guide
// (docs/guide/tester/): the behaviour gaps, the catalogue with its status,
// and the log of implemented scenarios, one page and one picture per file.
// The output is deterministic, so a test can tell when the committed pages
// fall behind the scenario files (TestBookCurrent; `make scenario-docs`).
package book

import (
	"bytes"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/kKEo/memors/internal/eval/scenario"
	"github.com/kKEo/memors/internal/eval/scenario/coverage"
	"github.com/kKEo/memors/internal/eval/scenario/diagram"
)

// Defaults, relative to the repository root.
const (
	DefaultDir       = "internal/eval/testdata/scenarios"
	DefaultCatalogue = "internal/eval/testdata/scenario-catalogue.yaml"
	DefaultBook      = "docs/guide/tester"
	// RepoURL prefixes repository paths in links: the guides may only link
	// inside docs/guide/ with relative links (scripts/docs-check.sh).
	RepoURL = "https://github.com/kKEo/memors/blob/master/"
	// LogDir holds the generated per-scenario pages; nothing else lives
	// there, so files the generator no longer produces are removed.
	LogDir = "scenarios/log"
	// SummaryAnchor is the SUMMARY.md line whose children are the
	// per-scenario pages.
	SummaryAnchor = "[Implemented scenarios](scenarios/log/README.md)"
)

// Config says where the inputs are.
type Config struct {
	Dir       string // the scenario files
	Catalogue string // the catalogue data file
	// SourcePath is Dir as a repository path, for links to the files on
	// GitHub (default DefaultDir).
	SourcePath string
	// CataloguePath is Catalogue as a repository path (default DefaultCatalogue).
	CataloguePath string
}

// Output is what Generate produces: files by path relative to the book
// root, and the per-scenario SUMMARY.md entries in order.
type Output struct {
	Files   map[string][]byte
	Entries []SummaryEntry
}

// SummaryEntry is one line under SummaryAnchor.
type SummaryEntry struct{ Title, Path string }

// Generate builds every generated page from the scenario files and the
// catalogue.
func Generate(cfg Config) (*Output, error) {
	if cfg.SourcePath == "" {
		cfg.SourcePath = DefaultDir
	}
	if cfg.CataloguePath == "" {
		cfg.CataloguePath = DefaultCatalogue
	}
	cat, err := coverage.LoadCatalogue(cfg.Catalogue)
	if err != nil {
		return nil, err
	}
	ix, err := coverage.Build(cfg.Dir, cat)
	if err != nil {
		return nil, err
	}
	g := &gen{cfg: cfg, cat: cat, ix: ix}
	out := &Output{Files: map[string][]byte{}}
	out.Files["scenarios/gaps.md"] = g.gaps()
	out.Files["scenarios/catalogue.md"] = g.catalogue()
	out.Files[LogDir+"/README.md"] = g.logIndex()
	for _, f := range ix.Files {
		page, svg, err := g.scenarioPage(f)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", f.Name, err)
		}
		out.Files[LogDir+"/"+f.Base+".md"] = page
		if svg != nil {
			out.Files[LogDir+"/"+f.Base+".svg"] = svg
		}
		out.Entries = append(out.Entries, SummaryEntry{Title: f.Base, Path: LogDir + "/" + f.Base + ".md"})
	}
	return out, nil
}

type gen struct {
	cfg Config
	cat *coverage.Catalogue
	ix  *coverage.Index
}

func (g *gen) banner(b *bytes.Buffer, from string) {
	fmt.Fprintf(b, "<!-- Generated by `memors-scenario book` from %s. Do not edit: change the source and run `make scenario-docs`. -->\n\n", from)
}

// cell makes text safe inside a markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "\r", "")
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.ReplaceAll(s, "|", `\|`)
}

// code wraps s in backticks, using a longer fence when s has one.
func code(s string) string {
	if s == "" {
		return ""
	}
	if strings.Contains(s, "`") {
		return "`` " + s + " ``"
	}
	return "`" + s + "`"
}

func anchor(id string) string { return strings.ToLower(id) }

// gapNumber turns gap-15 into 15.
func gapNumber(id string) string { return strings.TrimPrefix(strings.ToLower(id), "gap-") }

// ref links a covers id from a page in dir (scenarios or scenarios/log).
func (g *gen) ref(id, dir string) string {
	up := ""
	if dir == LogDir {
		up = "../"
	}
	k := strings.ToLower(id)
	for _, e := range g.cat.Entries {
		if strings.EqualFold(e.ID, id) {
			return fmt.Sprintf("[%s %s](%scatalogue.md#%s)", e.ID, e.Title, up, k)
		}
	}
	for _, gp := range g.cat.Gaps {
		if strings.EqualFold(gp.ID, id) {
			return fmt.Sprintf("[gap %s](%sgaps.md#%s)", gapNumber(gp.ID), up, k)
		}
	}
	return code(id) + " (not in the catalogue)"
}

// files links the scenario pages covering id, from a page in dir.
func (g *gen) files(id, dir string) []string {
	var out []string
	for _, base := range g.ix.CoveredBy[strings.ToLower(id)] {
		p := LogDir + "/" + base + ".md"
		switch dir {
		case LogDir:
			p = base + ".md"
		case "scenarios":
			p = "log/" + base + ".md"
		}
		out = append(out, fmt.Sprintf("[%s](%s)", base, p))
	}
	return out
}

func (g *gen) source(p string) string {
	return fmt.Sprintf("[%s](%s%s)", code(p), RepoURL, p)
}

func count(n int, one, many string) string {
	if n == 1 {
		return "1 " + one
	}
	return strconv.Itoa(n) + " " + many
}

// gaps is scenarios/gaps.md.
func (g *gen) gaps() []byte {
	var b bytes.Buffer
	b.WriteString("# Behaviour gaps\n\n")
	g.banner(&b, code(g.cfg.CataloguePath))
	pinned := len(g.cat.Gaps) - len(g.ix.UncoveredGaps)
	decided := 0
	for _, gp := range g.cat.Gaps {
		if gp.Decision != "open" {
			decided++
		}
	}
	fmt.Fprintf(&b, "Reading the code with scenarios in mind surfaced behaviours that no test pinned down. Some are bugs, some are decisions never taken. Each becomes a scenario tagged `decision: open` that asserts today's behaviour; the owner then decides per gap to keep it, change it, or document it only. A fix is a separate change whose scenario is shown failing first and then flips to `decided` (see [Open and decided](decisions.md)).\n\n")
	fmt.Fprintf(&b, "**%d gaps** · **%d pinned** by a scenario · **%d decided**\n\n", len(g.cat.Gaps), pinned, decided)
	b.WriteString("| # | Gap | Where | Decision | Pinned by |\n|---|---|---|---|---|\n")
	for _, gp := range g.cat.Gaps {
		by := strings.Join(g.files(gp.ID, "scenarios"), ", ")
		if by == "" {
			by = "not yet"
		}
		fmt.Fprintf(&b, "| [%s](#%s) | %s | %s | %s | %s |\n", gapNumber(gp.ID), anchor(gp.ID), cell(gp.Title), cell(gp.Where), cell(gp.Decision), by)
	}
	for _, gp := range g.cat.Gaps {
		fmt.Fprintf(&b, "\n<a id=\"%s\"></a>\n\n## Gap %s: %s\n\n%s\n\n", anchor(gp.ID), gapNumber(gp.ID), gp.Title, gp.Detail)
		fmt.Fprintf(&b, "- **Where:** %s\n- **Decision:** %s\n", gp.Where, gp.Decision)
		var entries []string
		n, _ := strconv.Atoi(gapNumber(gp.ID))
		for _, e := range g.cat.Entries {
			for _, x := range e.Gaps {
				if x == n {
					entries = append(entries, fmt.Sprintf("[%s %s](catalogue.md#%s)", e.ID, e.Title, anchor(e.ID)))
				}
			}
		}
		if len(entries) > 0 {
			fmt.Fprintf(&b, "- **Catalogue:** %s\n", strings.Join(entries, ", "))
		}
		if by := g.files(gp.ID, "scenarios"); len(by) > 0 {
			fmt.Fprintf(&b, "- **Pinned by:** %s\n", strings.Join(by, ", "))
		} else {
			b.WriteString("- **Pinned by:** no scenario yet\n")
		}
	}
	return b.Bytes()
}

func tierOf(e coverage.Entry) string {
	if e.Tier == "" {
		return "ci"
	}
	return e.Tier
}

// catalogue is scenarios/catalogue.md.
func (g *gen) catalogue() []byte {
	var b bytes.Buffer
	b.WriteString("# Catalogue\n\n")
	g.banner(&b, code(g.cfg.CataloguePath))
	done := len(g.cat.Entries) - len(g.ix.Uncovered)
	b.WriteString("The scenarios the harness should hold, grouped by what they stress. Each entry is a story: actors, steps over time, and what must be observable. A file implements an entry when its name starts with the entry's id (`b2-zombie-fact.yaml`) or its `covers:` names it. The tier says where the scenario will run: `ci` on every pull request with the hash embedder, `nightly` with a real model, `binary` against the built `memors-mcp` process.\n\n")
	fmt.Fprintf(&b, "**%d entries** · **%d implemented** · **%d planned**\n\n", len(g.cat.Entries), done, len(g.cat.Entries)-done)
	b.WriteString("| Id | Scenario | Tier | Gaps | Status |\n|---|---|---|---|---|\n")
	for _, e := range g.cat.Entries {
		status := "planned"
		if by := g.files(e.ID, "scenarios"); len(by) > 0 {
			status = "implemented: " + strings.Join(by, ", ")
		}
		fmt.Fprintf(&b, "| [%s](#%s) | %s | %s | %s | %s |\n", e.ID, anchor(e.ID), cell(e.Title), tierOf(e), g.gapLinks(e.Gaps), status)
	}
	var last string
	for _, e := range g.cat.Entries {
		c := g.cat.Category(e)
		if c.ID != last {
			last = c.ID
			fmt.Fprintf(&b, "\n## %s. %s\n", c.ID, c.Title)
			if c.Intro != "" {
				fmt.Fprintf(&b, "\n%s\n", c.Intro)
			}
		}
		fmt.Fprintf(&b, "\n<a id=\"%s\"></a>\n\n### %s %s\n\n%s\n\n", anchor(e.ID), e.ID, e.Title, e.Detail)
		fmt.Fprintf(&b, "- **Tier:** %s\n", tierOf(e))
		if len(e.Gaps) > 0 {
			fmt.Fprintf(&b, "- **Gaps:** %s\n", g.gapLinks(e.Gaps))
		}
		if by := g.files(e.ID, "scenarios"); len(by) > 0 {
			fmt.Fprintf(&b, "- **Status:** implemented by %s\n", strings.Join(by, ", "))
		} else {
			b.WriteString("- **Status:** planned\n")
		}
	}
	return b.Bytes()
}

func (g *gen) gapLinks(gaps []int) string {
	var parts []string
	for _, n := range gaps {
		parts = append(parts, fmt.Sprintf("[%d](gaps.md#gap-%d)", n, n))
	}
	return strings.Join(parts, ", ")
}

// logIndex is scenarios/log/README.md.
func (g *gen) logIndex() []byte {
	var b bytes.Buffer
	b.WriteString("# Implemented scenarios\n\n")
	g.banner(&b, code(g.cfg.SourcePath+"/")+" and "+code(g.cfg.CataloguePath))
	fmt.Fprintf(&b, "Every scenario file in %s, one page each with its story, its picture, its steps and its source. The pages are regenerated from the files, and a test fails when they fall behind, so this list is always what CI runs. Files on the `ci` tier run on every pull request in `TestScenarios` (`go test ./internal/eval/scenario/ -run TestScenarios`).\n\n", g.source(g.cfg.SourcePath))
	decisions := map[string]int{}
	tiers := map[string]int{}
	for _, f := range g.ix.Files {
		decisions[f.Decision]++
		for _, t := range f.Tiers {
			tiers[t]++
		}
	}
	done := len(g.cat.Entries) - len(g.ix.Uncovered)
	pinned := len(g.cat.Gaps) - len(g.ix.UncoveredGaps)
	fmt.Fprintf(&b, "**%s** · **%d of %d** [catalogue](../catalogue.md) entries implemented · **%d of %d** [gaps](../gaps.md) pinned · %s · %s\n\n",
		count(len(g.ix.Files), "scenario file", "scenario files"), done, len(g.cat.Entries), pinned, len(g.cat.Gaps), joinCounts(decisions, ""), joinCounts(tiers, " tier"))
	b.WriteString("| Scenario | Covers | What it checks | Decision | Tiers | Steps | Actors |\n|---|---|---|---|---|---|---|\n")
	for _, f := range g.ix.Files {
		var covers []string
		for _, c := range f.Covers {
			covers = append(covers, g.ref(c, LogDir))
		}
		title := f.Title
		if !f.OK() {
			title = "**invalid:** " + f.Error
		}
		steps := strconv.Itoa(f.Steps)
		if f.Parallel > 0 {
			steps += fmt.Sprintf(" (%d parallel)", f.Parallel)
		}
		fmt.Fprintf(&b, "| [%s](%s.md) | %s | %s | %s | %s | %s | %s |\n", f.Base, f.Base, strings.Join(covers, ", "), cell(title), f.Decision, strings.Join(f.Tiers, ", "), steps, strings.Join(f.Actors, ", "))
	}

	b.WriteString("\n## Coverage\n\nWhat the files above exercise, and what nobody has written yet. The same view is the index page of the [studio](../studio.md).\n")
	b.WriteString("\n### Operations by actor kind\n\nWhich scenarios call each operation as an agent (an MCP tool) and as a human (the CLI channel). A dash is a test nobody wrote yet.\n\n| Operation | As an agent | As a human |\n|---|---|---|\n")
	for _, o := range g.ix.Ops {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", code(o.Op), opCell(o.Agent, o.AgentNA, "not a tool"), opCell(o.Human, o.HumanNA, "not a CLI op"))
	}
	b.WriteString("\n### Expectation kinds\n\nSee [Writing scenarios](../dsl.md) for what each one checks.\n\n| Kind | Used by |\n|---|---|\n")
	for _, e := range g.ix.Expectations {
		fmt.Fprintf(&b, "| %s | %s |\n", code(e.Key), opCell(e.Scenarios, false, ""))
	}
	b.WriteString("\n### Invariants skipped\n\n")
	if len(g.ix.Skipped) == 0 {
		fmt.Fprintf(&b, "None: every scenario holds all %d [invariants](../invariants.md) after every step.\n", len(scenario.InvariantNames()))
	} else {
		b.WriteString("A skip documents a gap; every other invariant still runs. See [Invariants](../invariants.md).\n\n| Invariant | Skipped by |\n|---|---|\n")
		for _, s := range g.ix.Skipped {
			fmt.Fprintf(&b, "| %s | %s |\n", code(s.Key), strings.Join(s.Scenarios, ", "))
		}
	}
	b.WriteString("\n### Not covered yet\n\n")
	var ids []string
	for _, e := range g.ix.Uncovered {
		ids = append(ids, fmt.Sprintf("[%s](../catalogue.md#%s)", e.ID, anchor(e.ID)))
	}
	fmt.Fprintf(&b, "- **Catalogue entries (%d):** %s\n", len(ids), orNone(ids))
	ids = nil
	for _, gp := range g.ix.UncoveredGaps {
		ids = append(ids, fmt.Sprintf("[%s](../gaps.md#%s)", gapNumber(gp.ID), anchor(gp.ID)))
	}
	fmt.Fprintf(&b, "- **Gaps (%d):** %s\n", len(ids), orNone(ids))
	if len(g.ix.Unknown) > 0 {
		b.WriteString("\n### Unknown `covers` ids\n\nThese ids are not in the catalogue, so nothing counts them. Add them to the catalogue or fix the file.\n\n")
		for _, u := range g.ix.Unknown {
			fmt.Fprintf(&b, "- %s in %s\n", code(u.Key), strings.Join(u.Scenarios, ", "))
		}
	}
	return b.Bytes()
}

func opCell(list []string, na bool, naText string) string {
	switch {
	case na:
		return "*" + naText + "*"
	case len(list) == 0:
		return "—"
	}
	links := make([]string, len(list))
	for i, s := range list {
		links[i] = fmt.Sprintf("[%s](%s.md)", s, s)
	}
	return strings.Join(links, ", ")
}

func orNone(list []string) string {
	if len(list) == 0 {
		return "none"
	}
	return strings.Join(list, " · ")
}

func joinCounts(m map[string]int, suffix string) string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = fmt.Sprintf("%d %s%s", m[k], k, suffix)
	}
	return strings.Join(parts, ", ")
}

// scenarioPage is scenarios/log/<base>.md and its picture.
func (g *gen) scenarioPage(f coverage.File) ([]byte, []byte, error) {
	var b bytes.Buffer
	srcPath := g.cfg.SourcePath + "/" + f.Name
	fmt.Fprintf(&b, "# %s\n\n", f.Base)
	g.banner(&b, code(srcPath))
	if f.Title != "" {
		fmt.Fprintf(&b, "*%s*\n\n", f.Title)
	}
	sc := f.Sc
	if !f.OK() {
		b.WriteString("> **This file is invalid** and does not run. Problems:\n>\n")
		for _, is := range f.Issues {
			if is.Line > 0 {
				fmt.Fprintf(&b, "> - line %d: %s\n", is.Line, is.Msg)
			} else {
				fmt.Fprintf(&b, "> - %s\n", is.Msg)
			}
		}
		b.WriteString("\n")
	}
	if sc != nil {
		if sc.Name != f.Base {
			fmt.Fprintf(&b, "- **Name:** %s\n", code(sc.Name))
		}
		if f.Decision == "open" {
			b.WriteString("- **Decision:** open: the expectations pin today's behaviour of a documented gap, not the behaviour anyone has chosen ([Open and decided](../decisions.md))\n")
		} else {
			b.WriteString("- **Decision:** decided: the expectations are the wanted behaviour ([Open and decided](../decisions.md))\n")
		}
		fmt.Fprintf(&b, "- **Tiers:** %s\n", strings.Join(f.Tiers, ", "))
		if len(f.Covers) > 0 {
			var covers []string
			for _, c := range f.Covers {
				covers = append(covers, g.ref(c, LogDir))
			}
			fmt.Fprintf(&b, "- **Covers:** %s\n", strings.Join(covers, " · "))
		}
		var actors []string
		for _, k := range diagram.ActorOrder(sc) {
			a := sc.Actors[k]
			s := code(k) + " " + a.Kind
			if a.Client != "" && a.Client != k {
				s += ", client " + code(a.Client)
			}
			if a.Elicitation != "" && a.Elicitation != "none" {
				s += ", answers dialogs: " + a.Elicitation
			}
			actors = append(actors, s)
		}
		fmt.Fprintf(&b, "- **Actors:** %s\n", strings.Join(actors, " · "))
		start, _ := sc.ClockStart()
		fmt.Fprintf(&b, "- **Length:** %s over %s from %s\n", count(len(sc.Steps), "step", "steps"), diagram.Span(sc), start.Format("2006-01-02"))
	}
	fmt.Fprintf(&b, "- **Source:** %s\n", g.source(srcPath))
	if f.Lead != "" {
		fmt.Fprintf(&b, "\n## Why it exists\n\n%s\n", f.Lead)
	}
	var svg []byte
	if sc != nil {
		var err error
		svg, err = diagram.Render(sc, diagram.Options{Mode: diagram.Standalone, Expand: diagram.ParseExpand("all"), Issues: f.Issues})
		if err != nil {
			return nil, nil, err
		}
		fmt.Fprintf(&b, "\n## Picture\n\n![Swimlane picture of %s](%s.svg)\n\n[Open the picture on its own](%s.svg) to zoom. [Reading the picture](../pictures.md) explains lanes, chips and edges.\n", f.Base, f.Base, f.Base)
		g.steps(&b, sc)
		b.WriteString("\n## Invariants\n\n")
		skips := skipsOf(sc)
		if len(skips) == 0 {
			fmt.Fprintf(&b, "All %d [invariants](../invariants.md) run after every step.\n", len(scenario.InvariantNames()))
		} else {
			fmt.Fprintf(&b, "All %d [invariants](../invariants.md) run after every step, except:\n\n", len(scenario.InvariantNames()))
			for _, s := range skips {
				fmt.Fprintf(&b, "- %s\n", s)
			}
		}
	}
	src := strings.TrimRight(string(f.Source), "\n")
	fmt.Fprintf(&b, "\n## Source\n\n<details>\n<summary>%s (%s)</summary>\n\n```yaml\n%s\n```\n\n</details>\n", f.Name, count(strings.Count(src, "\n")+1, "line", "lines"), src)
	return b.Bytes(), svg, nil
}

func skipsOf(sc *scenario.Scenario) []string {
	var out []string
	if sc.Invariants != nil {
		for _, s := range sc.Invariants.Skip {
			out = append(out, code(s)+" for the whole scenario")
		}
	}
	for i, st := range sc.Steps {
		if st.Invariants != nil {
			for _, s := range st.Invariants.Skip {
				out = append(out, fmt.Sprintf("%s after step %d", code(s), i+1))
			}
		}
		for j, sub := range st.Parallel {
			if sub.Invariants != nil {
				for _, s := range sub.Invariants.Skip {
					out = append(out, fmt.Sprintf("%s after step %d.%d", code(s), i+1, j+1))
				}
			}
		}
	}
	return out
}

// steps writes the step table: one row per step, parallel sub-steps as n.m.
func (g *gen) steps(b *bytes.Buffer, sc *scenario.Scenario) {
	b.WriteString("\n## Steps\n\n| # | When | Actor | Op | What | Bind | Expects |\n|---|---|---|---|---|---|---|\n")
	start, _ := sc.ClockStart()
	var off time.Duration
	when := func(at string) string {
		w := start.Add(off).Format("Jan 2")
		if at != "" {
			w += " (" + at + ")"
		}
		return w
	}
	what := func(gist, note string) string {
		out := plain(gist)
		if note != "" {
			if out != "" {
				out += "<br>"
			}
			out += "*" + plain(note) + "*"
		}
		return out
	}
	row := func(num, w string, st scenario.Step, p string) {
		bind := ""
		if st.Bind != "" {
			bind = code("$" + st.Bind)
		}
		op := code(st.Op)
		if st.Elicit != "" {
			op += " (dialog: " + st.Elicit + ")"
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s | %s |\n", num, w, code(st.Actor), op, what(diagram.Gist(st, sc.Lines, p), st.Note), bind, strings.Join(coverage.ExpectKinds(st.Expect), ", "))
	}
	for i, st := range sc.Steps {
		if st.At != "" {
			if d, err := scenario.ParseAt(st.At); err == nil {
				off = d
			}
		}
		if len(st.Parallel) == 0 {
			row(strconv.Itoa(i+1), when(st.At), st, scenario.StepPath(i, -1))
			continue
		}
		fmt.Fprintf(b, "| %d | %s | | *parallel* | %s | | |\n", i+1, when(st.At), what(count(len(st.Parallel), "sub-step at once", "sub-steps at once"), st.Note))
		for j, sub := range st.Parallel {
			row(fmt.Sprintf("%d.%d", i+1, j+1), "", sub, scenario.StepPath(i, j))
		}
	}
}

// plain makes free text safe in a markdown table cell: no markup, no pipes,
// no line breaks.
func plain(s string) string {
	var sb strings.Builder
	for _, r := range s {
		switch r {
		case '\\', '`', '*', '_', '[', ']', '<', '>', '#':
			sb.WriteRune('\\')
		}
		sb.WriteRune(r)
	}
	return cell(sb.String())
}

// SpliceSummary replaces the lines under SummaryAnchor that are indented
// deeper than it with one line per entry.
func SpliceSummary(summary []byte, entries []SummaryEntry) ([]byte, error) {
	lines := strings.Split(string(summary), "\n")
	at := -1
	for i, l := range lines {
		if strings.HasSuffix(strings.TrimRight(l, " "), SummaryAnchor) && strings.HasPrefix(strings.TrimSpace(l), "- ") {
			at = i
			break
		}
	}
	if at < 0 {
		return nil, fmt.Errorf("SUMMARY.md has no line ending in %q", SummaryAnchor)
	}
	indent := len(lines[at]) - len(strings.TrimLeft(lines[at], " "))
	end := at + 1
	for end < len(lines) {
		l := lines[end]
		if strings.TrimSpace(l) == "" || len(l)-len(strings.TrimLeft(l, " ")) <= indent {
			break
		}
		end++
	}
	child := strings.Repeat(" ", indent+2) + "- "
	var add []string
	for _, e := range entries {
		add = append(add, fmt.Sprintf("%s[%s](%s)", child, e.Title, e.Path))
	}
	out := append(append(append([]string{}, lines[:at+1]...), add...), lines[end:]...)
	return []byte(strings.Join(out, "\n")), nil
}

// Change is one file the book needs: Content nil means remove it.
type Change struct {
	Path    string // relative to the book root, slash-separated
	Content []byte
}

// Plan compares the generated output with the book at root and lists the
// changes that would bring it up to date: new or different files, the
// SUMMARY.md splice, and files under LogDir the generator no longer makes.
func Plan(root string, out *Output) ([]Change, error) {
	var changes []Change
	paths := make([]string, 0, len(out.Files))
	for p := range out.Files {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		have, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p)))
		if err != nil || !bytes.Equal(have, out.Files[p]) {
			changes = append(changes, Change{Path: p, Content: out.Files[p]})
		}
	}
	summary, err := os.ReadFile(filepath.Join(root, "SUMMARY.md"))
	if err != nil {
		return nil, err
	}
	spliced, err := SpliceSummary(summary, out.Entries)
	if err != nil {
		return nil, err
	}
	if !bytes.Equal(summary, spliced) {
		changes = append(changes, Change{Path: "SUMMARY.md", Content: spliced})
	}
	ents, err := os.ReadDir(filepath.Join(root, filepath.FromSlash(LogDir)))
	if err != nil && !os.IsNotExist(err) {
		return nil, err
	}
	for _, e := range ents {
		p := path.Join(LogDir, e.Name())
		ext := path.Ext(p)
		if e.IsDir() || (ext != ".md" && ext != ".svg") {
			continue
		}
		if _, ok := out.Files[p]; !ok {
			changes = append(changes, Change{Path: p})
		}
	}
	return changes, nil
}

// Apply writes and removes files under root.
func Apply(root string, changes []Change) error {
	for _, c := range changes {
		p := filepath.Join(root, filepath.FromSlash(c.Path))
		if c.Content == nil {
			if err := os.Remove(p); err != nil {
				return err
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, c.Content, 0o644); err != nil {
			return err
		}
	}
	return nil
}
